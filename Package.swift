// swift-tools-version: 6.0

import Foundation
import PackageDescription

// Internal tooling (native-dev): inert unless both variables are set. During a
// native dev-source window the Octopus package resolves from one revision of
// another repository; SwiftPM names a package after its URL, so the product
// references follow that name.
let octopusDevEnvironment = ProcessInfo.processInfo.environment
let octopusDevURL = octopusDevEnvironment["OCTOPUS_IOS_DEV_PACKAGE_URL"] ?? ""
let octopusDevRevision = octopusDevEnvironment["OCTOPUS_IOS_DEV_REVISION"] ?? ""
let octopusUsesDevRevision = !octopusDevURL.isEmpty && !octopusDevRevision.isEmpty
let octopusPackage: Package.Dependency = octopusUsesDevRevision
    ? .package(url: octopusDevURL, revision: octopusDevRevision)
    // Keep the exact pin equal to octopus_version in the podspec.
    : .package(url: "https://github.com/Octopus-Community/octopus-sdk-swift.git", exact: "1.15.0")
let octopusPackageName = octopusUsesDevRevision
    ? (URL(string: octopusDevURL)?.deletingPathExtension().lastPathComponent ?? "")
    : "octopus-sdk-swift"

let package = Package(
    name: "OctopusReactNativeSdk",
    // RN 0.87's generated Autolinked aggregate declares .iOS(.v15); a higher
    // package minimum fails resolution. The app's deployment target still applies.
    platforms: [.iOS(.v15)],
    products: [
        .library(name: "OctopusReactNativeSdk", targets: ["OctopusReactNativeSdk"])
    ],
    dependencies: [
        // RN 0.87 references this manifest through
        // ios/build/generated/autolinking/libs/OctopusReactNativeSdk/.
        // React's headers come from the app-local package generated by `react-native spm`.
        .package(name: "ReactNative", path: "../../../../xcframeworks"),
        octopusPackage
    ],
    targets: [
        .target(
            name: "OctopusReactNativeSdkSwift",
            dependencies: [
                .product(name: "ReactHeaders", package: "ReactNative"),
                .product(name: "Octopus", package: octopusPackageName),
                .product(name: "OctopusUI", package: octopusPackageName)
            ],
            path: "ios",
            exclude: [
                "OctopusReactNativeSdk.mm",
                "OctopusUIViewManager.m",
                "OctopusReactNativeSdk-Bridging-Header.h",
                "spm"
            ]
        ),
        // SwiftPM requires separate Swift and Clang targets. The extern categories
        // register the @objc classes without importing a generated Swift header,
        // so only this target depends on the Swift implementation.
        .target(
            name: "OctopusReactNativeSdk",
            dependencies: [
                "OctopusReactNativeSdkSwift",
                .product(name: "ReactHeaders", package: "ReactNative")
            ],
            path: "ios",
            sources: ["OctopusReactNativeSdk.mm", "OctopusUIViewManager.m"],
            publicHeadersPath: "spm/include"
        )
    ],
    swiftLanguageModes: [.v5],
    cxxLanguageStandard: .cxx20
)
